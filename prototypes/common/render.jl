# Helpers for rendering a client from the parsed spec in spec.jl, shared by the custom generators.
# Each helper returns a string of code or documentation, so a generator is a list of the pieces it joins:
#
#     join([header(...), docstring(...), "module X\n", runtime(COMMON_RUNTIME, "formats.jl"), ...], "\n")
#
# Code that is emitted unchanged lives in real Julia files, read with `runtime`: the pieces every HTTP.jl client shares are in prototypes/common/runtime/, and each client's own pieces in its gen/runtime/.

import SHA

const COMMON_RUNTIME = joinpath(@__DIR__, "runtime")

"The contents of the runtime file `name` in `dir`, to emit unchanged."
runtime(dir, name) = read(joinpath(dir, name), String)

"The generated file's header: what generated it, from which spec."
function header(generator, spec, spec_bytes, ops)
    info = spec["info"]
    return """
        # This file is generated by $generator from prototypes/common/openapi.json.
        # Do not edit it.
        # Spec: $(info["title"]) $(info["version"]) (OpenAPI $(spec["openapi"])), $(length(ops)) operations, sha256 $(bytes2hex(SHA.sha256(spec_bytes)))
        """
end

"`const BASE_URL = ...`, the API's base URL."
base_url() = "const BASE_URL = $(repr(BASE_URL))\n"

"`const MIMES = ...`, the response formats by their shorthand."
mimes() = "const MIMES = Dict(" * join(["$(repr(s)) => $(repr(m))" for (m, s) in FORMATS], ", ") * ")\n"

"The format shorthands as a Markdown list, for docstrings: \"`:json`, `:xml`, ...\"."
format_shorthands() = join(["`$(repr(s))`" for (_, s) in FORMATS], ", ")

"A Markdown table with a header row and one row per entry of `rows`."
function table(columns, rows)
    lines = ["| " * join(columns, " | ") * " |",
             "|" * join([":" * "-"^(length(c) + 1) for c in columns], "|") * "|"]
    append!(lines, ["| " * join(row, " | ") * " |" for row in rows])
    return join(lines, "\n")
end

"A `\"\"\"`-delimited docstring around `text`."
docstring(text) = "\"\"\"\n" * text * "\n\"\"\"\n"

# Text placed inside a "..." docstring.
function doctext(s)
    s = replace(s, "\r\n" => "\n")
    s = replace(s, "\\" => "\\\\")
    s = replace(s, "\$" => "\\\$")
    s = replace(s, "\"" => "\\\"")
    return join(rstrip.(split(s, '\n')), "\n")
end

camel(name) = join(uppercasefirst.(split(name, '_')))

function default_accept(op)
    "application/json" in op.formats && return ":json"
    isempty(op.formats) && return ":json"
    f = op.formats[1]
    for (mime, sym) in FORMATS
        mime == f && return repr(sym)
    end
    return repr(f)
end

# The Julia type a parameter accepts, or "" for no restriction.
# Many string parameters are integers or comma-separated lists in disguise (`taxid` has pattern ^[0-9]+(,[0-9]+)*$), so those also accept an Integer or a Vector; the aliases are defined in runtime/parameters.jl.
function julia_type(p)
    s = p.schema
    t = get(s, "type", "")
    t == "integer" && return "Integer"
    t == "number" && return "Real"
    t == "boolean" && return "Bool"
    t == "array" && return "AbstractVector"
    t == "string" || return ""
    pattern = get(s, "pattern", "")
    pattern == "true|false" && return "Bool"
    numeric = startswith(lstrip(pattern, '^'), "[0-9]+")
    if occursin("(,", pattern)
        return numeric ? "IntListParam" : "ListParam"
    end
    return numeric ? "IntParam" : "AbstractString"
end

optional_type(T) = isempty(T) ? "" : "::Union{Nothing, $T}"
required_type(T) = isempty(T) ? "" : "::$T"

"A struct field for parameter `p`: required, or optional with the default `nothing`."
function field(p; untyped = "Any")
    T = julia_type(p)
    T = isempty(T) ? untyped : T
    return p.required ? "$(p.name)::$T" : "$(p.name)::Union{Nothing, $T} = nothing"
end

function param_doc(p)
    s = p.schema
    bits = String[]
    t = get(s, "type", "")
    isempty(t) || push!(bits, haskey(s, "format") ? "$t/$(s["format"])" : t)
    p.required && p.location == "query" && push!(bits, "required")
    haskey(s, "default") && push!(bits, "default `$(JSON.json(s["default"]))`")
    haskey(s, "enum") && push!(bits, "one of " * join(["`$(v)`" for v in s["enum"]], ", "))
    haskey(s, "pattern") && push!(bits, "pattern `$(s["pattern"])`")
    T = julia_type(p)
    line = "- `$(p.name)$(required_type(T))`" * (isempty(bits) ? "" : " (spec: " * join(bits, "; ") * ")")
    isempty(p.description) || (line *= ": " * replace(strip(p.description), r"\s*\n\s*" => " "))
    return line
end

pageable(op) = op.method == "GET" && all(n -> any(p -> p.name == n, op.queryparams), ("offset", "size"))

"""
The docstring of an operation, shared by the custom generators: its signature, summary, endpoint, parameters and response formats.
`headings` names the sections for path parameters (and body) and for query parameters, and `body` describes the request body argument.
"""
function operation_doc(op, signature, headings, body)
    blocks = ["    " * signature]
    isempty(op.summary) || push!(blocks, doctext(op.summary))
    isempty(op.description) || op.description == op.summary || push!(blocks, doctext(op.description))
    tag = isempty(op.tags) ? "" : ", tag `$(op.tags[1])`"
    push!(blocks, "`$(op.method) $(op.path)` (operationId `$(op.operation_id)`$tag)")
    op.deprecated && push!(blocks, "**Deprecated** in the API specification.")
    if !isempty(op.pathparams) || op.body !== nothing
        lines = [doctext(param_doc(p)) for p in op.pathparams]
        op.body === nothing || push!(lines, "- `body`: request body, $(doctext(op.body)); $body")
        push!(blocks, "# $(headings[1])\n" * join(lines, "\n"))
    end
    if !isempty(op.queryparams)
        push!(blocks, "# $(headings[2])\n" * join([doctext(param_doc(p)) for p in op.queryparams], "\n"))
    end
    response = ["# Response"]
    push!(response, "Formats listed in the spec: " * (isempty(op.formats) ? "none" : join(["`$f`" for f in op.formats], ", ")) * ".")
    isempty(op.response) || push!(response, "JSON schema: `$(op.response)`.")
    pageable(op) && push!(response, "Searches can be iterated page by page with `paginate`.")
    push!(blocks, join(response, "\n"))
    return join(blocks, "\n\n")
end
