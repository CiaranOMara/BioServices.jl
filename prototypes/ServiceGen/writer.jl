# Write a client from a `Service` description: one `JSON.@kwarg` request type per operation, over the shared runtime in prototypes/ServiceRuntime.
# The client holds only the service's settings, its request types and their documentation; everything that runs a request is in the runtime.
# Each function returns a string of code or documentation, and `render` joins them.

# The text helpers the other custom generators use: `table`, `docstring`, `doctext` and `camel`.
include(joinpath(@__DIR__, "..", "common", "render.jl"))

"The generated module for service `s`, described by the file whose bytes are `bytes`."
function render(s::Service, source, bytes)
    return join([
        generated_header(s, source, bytes),
        docstring(service_doc(s)) * "module $(s.name)\n",
        "import ServiceRuntime as R\nusing ServiceRuntime: Endpoint, ListParam, send, url, paginate\nusing ServiceRuntime.JSON: @kwarg, StructUtils\n",
        settings(s),
        map(operation_code, s.operations)...,
        "end # module\n",
    ], "\n")
end

function generated_header(s, source, bytes)
    n = length(s.operations)
    return """
        # This file is generated by prototypes/ServiceGen/generate.jl from $source.
        # Do not edit it.
        # Service: $(s.title), $n operation$(n == 1 ? "" : "s"), sha256 $(bytes2hex(SHA.sha256(bytes)))
        """
end

"The service type and its methods for each setting that differs from the runtime's default."
function settings(s)
    lines = ["\"The $(s.name) service, the type its endpoints dispatch on.\"",
             "struct Service <: R.Service end",
             "",
             "R.base_url(::Service) = $(repr(s.base_url))",
             "R.formats(::Service) = (" * join(["$k = $(repr(v))" for (k, v) in s.formats], ", ") * (length(s.formats) == 1 ? ",)" : ")"),
             "R.defaultformat(::Service) = :$(s.formats[1][1])"]
    s.format_by == "header" || push!(lines, "R.formatby(::Service) = " * format_by(s.format_by))
    isempty(s.auth) || push!(lines, "R.auth(::Service) = " * auth(s.auth))
    isempty(s.paging) || push!(lines, "R.paging(::Service) = " * paging(s.paging))
    s.envelope === nothing || push!(lines, "R.envelope(::Service) = $(repr(s.envelope))")
    isempty(s.errors) || push!(lines, "R.errors(::Service) = " * errors(s.errors))
    return join(lines, "\n") * "\n"
end

format_by(f) = f == "extension" ? "R.ByExtension()" : "R.ByQuery($(repr(f[length("query:")+1:end])))"

function auth(a)
    kind = a["in"] == "query" ? "QueryKey" : a["in"] == "header" ? "HeaderKey" : error("auth: in must be query or header")
    return "R.$kind($(repr(a["name"])), $(repr(a["env"])))"
end

function paging(p)
    p["style"] == "page" || error("paging: style $(p["style"]) is not supported; the runtime has page")
    return "R.PageNumber($(repr(p["number"])), $(repr(p["size"])), $(repr(p["count"])))"
end

function errors(e)
    text = get(e, "text", nothing)
    return "R.ErrorRule($(repr(get(e, "json_field", nothing))), $(repr(get(e, "json_ok", nothing))), " *
           (text === nothing ? "nothing" : "r" * repr(text)) * ")"
end

"The Julia type of a parameter's values."
function value_type(p)
    p.type == "string" && return "String"
    p.type == "integer" && return "Int"
    p.type == "boolean" && return "Bool"
    return "ListParam"
end

"A struct field for parameter `p`, with its default and its tags."
function kwarg_field(p)
    T = value_type(p)
    decl = p.literal !== nothing ? "$(p.name)::Bool = false" :
           p.default !== nothing ? "$(p.name)::$T = $(repr(p.default))" :
           p.required ? "$(p.name)::$T" : "$(p.name)::Union{Nothing, $T} = nothing"
    tags = String[]
    p.location == "path" && push!(tags, "in = :path")
    p.literal === nothing || push!(tags, "literal = $(repr(p.literal))")
    p.sep === nothing || push!(tags, "sep = $(repr(p.sep))")
    return isempty(tags) ? decl : decl * " &(" * join(tags, ", ") * ",)"
end

"One operation's `@kwarg` struct and its path template."
function operation_code(op)
    T = camel(op.name)
    return docstring(operation_doc(op)) *
           "@kwarg struct $T <: Endpoint{Service, :$(op.method)}\n" *
           join(["    $(kwarg_field(p))\n" for p in op.params]) *
           "end\n" *
           "R.template(::Type{<:$T}) = $(repr(op.path))\n"
end

function param_line(p)
    T = p.literal === nothing ? value_type(p) : "Bool"
    bits = String[]
    p.default === nothing || push!(bits, "default `$(repr(p.default))`")
    p.required && p.location == "query" && push!(bits, "required")
    p.literal === nothing || push!(bits, "the segment `$(p.literal)` when `true`")
    p.location == "path" && !p.required && p.default === nothing && p.literal === nothing && push!(bits, "its segment is left out when `nothing`")
    isempty(p.enum) || push!(bits, "one of " * join(["`$(repr(v))`" for v in p.enum], ", "))
    p.sep === nothing || push!(bits, "a vector is joined with `$(p.sep)`")
    line = "- `$(p.name)::$T`" * (isempty(bits) ? "" : " (" * join(bits, "; ") * ")")
    # Further sentences of a description stay one per line, indented to continue the list item.
    isempty(p.description) || (line *= ": " * replace(p.description, r"\s*\n\s*" => "\n  "))
    return doctext(line)
end

function operation_doc(op)
    names = [p.name for p in op.params]
    blocks = ["    " * camel(op.name) * (isempty(names) ? "()" : "(; " * join(names, ", ") * ")")]
    isempty(op.summary) || push!(blocks, doctext(op.summary))
    isempty(op.description) || push!(blocks, doctext(op.description))
    push!(blocks, "`$(op.method) $(op.path)`")
    for (location, heading) in (("path", "Path fields"), ("query", "Query fields"))
        ps = filter(p -> p.location == location, op.params)
        isempty(ps) || push!(blocks, "# $heading\n" * join(map(param_line, ps), "\n"))
    end
    return join(blocks, "\n\n")
end

function service_doc(s)
    lines = ["Client for $(s.title), generated by prototypes/ServiceGen from a hand-written description, with one `JSON.@kwarg` request type per operation over the shared runtime in `ServiceRuntime`."]
    isempty(s.docs) || push!(lines, "API documentation: $(s.docs)")
    push!(lines, "",
          "Construct a request with its keyword constructor, then run it with `send(e)`, decode it into a type with `send(e, T)`, or see its URL with `url(e)`.",
          "Path segments and query parameters are both fields.",
          "A query field that is `nothing` is not sent, and an optional path field that is `nothing` leaves its segment out of the path.",
          "",
          "Response formats: " * join(["`:$k` (`$v`)" for (k, v) in s.formats], ", ") * "; `:$(s.formats[1][1])` is the default, and `accept` chooses another.",
          "The format is requested " * (s.format_by == "header" ? "with an `Accept` header." :
                                         s.format_by == "extension" ? "as an extension on the path, as in `.$(s.formats[1][1])`." :
                                         "with the query parameter `$(s.format_by[length("query:")+1:end])`."))
    isempty(s.auth) || push!(lines, "Requests need an API key, read from `ENV[\"$(s.auth["env"])\"]` and sent as the $(s.auth["in"]) parameter `$(s.auth["name"])`; `url(e)` leaves it out.")
    s.envelope === nothing || push!(lines, "JSON responses wrap the result in an object; `send` returns its `$(s.envelope)` field.")
    isempty(s.paging) || push!(lines, "Requests with a `$(s.paging["number"])` field can be iterated page by page with `paginate`.")
    isempty(s.errors) || push!(lines, "Errors the service reports in a successful response are thrown as `ServiceRuntime.ServiceError`.")
    push!(lines, "", "Base URL: $(s.base_url)", "",
          table(["Type", "Endpoint"], [["`$(camel(op.name))`", "`$(op.method) $(op.path)`"] for op in s.operations]))
    return join(lines, "\n")
end
