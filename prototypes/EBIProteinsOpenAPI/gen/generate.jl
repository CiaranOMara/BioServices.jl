# Generate prototypes/EBIProteinsOpenAPI/src/EBIProteinsOpenAPI.jl with OpenAPI.jl 1.x's native generator, from the spec snapshot in prototypes/common/:
#
#   julia --project=prototypes/EBIProteinsOpenAPI/gen -e 'using Pkg; Pkg.instantiate()'
#   julia --project=prototypes/EBIProteinsOpenAPI/gen prototypes/EBIProteinsOpenAPI/gen/generate.jl
#
# It has its own environment (gen/Project.toml), because OpenAPI.jl 1.x needs Julia 1.10 and JSON 1.x.
#
# OpenAPI.jl rejects the published spec, so its defects are patched first, and the base URL is added as `servers`.
module EBIProteinsOpenAPIGenerator

using OpenAPI
import JSON
import SHA

const SPEC_PATH = joinpath(@__DIR__, "..", "..", "common", "openapi.json")
# The spec has no `servers` entry, so the base URL is supplied here.
const BASE_URL = "https://www.ebi.ac.uk/proteins/api"
# Some query parameters carry their description as their `name`; these are the names the service actually accepts.
const QUERY_NAME_FIXUPS = [
    "Category type(s):" => "categories",
    "Feature type(s):" => "types",
    "PTM Confidence score(s):" => "confidence_score",
]

const GENERATOR = "prototypes/EBIProteinsOpenAPI/gen/generate.jl"
const OUT_PATH = normpath(joinpath(@__DIR__, "..", "src", "EBIProteinsOpenAPI.jl"))

function patch!(spec)
    for (path, item) in spec["paths"], (_, op) in item
        names = [m[1] for m in eachmatch(r"\{([^}]+)\}", path)]
        i = 0
        for p in get(op, "parameters", [])
            if p["in"] == "path"
                i += 1
                p["name"] = names[i]               # some names don't match the path template
                delete!(p, "style")                # `form` is not a valid style for path parameters
            elseif p["in"] == "query"
                for (prefix, fixed) in QUERY_NAME_FIXUPS
                    startswith(p["name"], prefix) && (p["name"] = fixed)
                end
            end
        end
    end
    spec["servers"] = [Dict("url" => BASE_URL)]
    return spec
end

function generate()
    bytes = read(SPEC_PATH)
    spec = patch!(JSON.parse(String(copy(bytes)); dicttype = Dict{String, Any}))
    mktempdir() do dir
        patched = joinpath(dir, "openapi.json")
        out = joinpath(dir, "EBIProteinsOpenAPI.jl")
        write(patched, JSON.json(spec))
        OpenAPI.client(patched; name = "EBIProteinsOpenAPI", path = out)
        open(OUT_PATH, "w") do io
            println(io, "# This file is generated by ", GENERATOR, " from prototypes/common/openapi.json ",
                    "(sha256 ", bytes2hex(SHA.sha256(bytes)), ").")
            println(io, "# Do not edit it.")
            write(io, read(out))
        end
    end
    println("wrote ", OUT_PATH)
end

end # module

abspath(PROGRAM_FILE) == (@__FILE__) && EBIProteinsOpenAPIGenerator.generate()
