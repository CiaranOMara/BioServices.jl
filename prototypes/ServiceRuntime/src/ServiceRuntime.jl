"""
    ServiceRuntime

The runtime that clients generated by prototypes/ServiceGen share, so a generated client holds only its service's settings, its request types and their documentation.

A generated client defines a singleton subtype of `Service` and gives it methods for the settings that differ between services:
- `base_url(s)`, the URL every path is appended to;
- `formats(s)`, the response formats as a `NamedTuple` of shorthand to MIME type, and `defaultformat(s)`;
- `formatby(s)`, how a format is requested: `ByHeader()`, `ByExtension()` or `ByQuery(name)`;
- `auth(s)`, how a request is authorised: `NoAuth()`, `QueryKey(name, env)` or `HeaderKey(name, env)`;
- `paging(s)`, how a list is paged: `NoPaging()` or `PageNumber(number, size, count)`;
- `envelope(s)`, the field of a JSON response that holds the result, or `nothing`;
- `errors(s)`, how a failed request that still returns HTTP 200 is recognised: `NoErrors()` or `ErrorRule(...)`.

Each strategy is a type, and the runtime dispatches on it, so a new service needs a new strategy only when it differs from every service before it.

Each operation is a `JSON.@kwarg` struct, a subtype of `Endpoint{S, M}` for its service `S` and HTTP method `M`, with a `template` method for its path.
Construct one, then:
- `send(e; accept, parse)` runs it, and `send(e, T)` decodes the response into `T`;
- `url(e)` is its full URL, without credentials;
- `paginate(e)` iterates over a list page by page, for services with a paging strategy.
"""
module ServiceRuntime

import HTTP
import JSON
using JSON: StructUtils

export send, url, paginate, ListParam


# Services and their strategies
# -----------------------------

"""
    Service

Supertype of the singleton types that stand for a service, one per generated client.
"""
abstract type Service end

"The URL every request path of service `s` is appended to."
function base_url end

"The response formats of service `s`, as a `NamedTuple` of shorthand to MIME type."
formats(::Service) = (json = "application/json",)

"The format requested when `send` is given no `accept`."
defaultformat(::Service) = :json

"The field of a JSON response that holds the result, or `nothing` when the response is the result."
envelope(::Service) = nothing

"Request a format with an `Accept` header."
struct ByHeader end
"Request a format by appending its shorthand to the path as an extension, as in `/hg38/TTCATT.json`."
struct ByExtension end
"Request a format with the query parameter `name`, set to its shorthand."
struct ByQuery
    name::String
end

"How service `s` is asked for a response format."
formatby(::Service) = ByHeader()

"Send no credentials."
struct NoAuth end
"Send an API key, read from the environment variable `env`, as the query parameter `name`."
struct QueryKey
    name::String
    env::String
end
"Send an API key, read from the environment variable `env`, as the header `name`."
struct HeaderKey
    name::String
    env::String
end

"How requests to service `s` are authorised."
auth(::Service) = NoAuth()

"Lists come in one response."
struct NoPaging end
"""
Lists are paged by number: the query parameters `number` and `size` choose a page, and the JSON response field `count` gives the number of pages.
"""
struct PageNumber
    number::String
    size::String
    count::String
end

"How lists from service `s` are paged."
paging(::Service) = NoPaging()

"Failed requests are recognised by their HTTP status alone."
struct NoErrors end
"""
Failed requests can also return HTTP 200.
They are recognised by a JSON object whose `json_field` is present and not `json_ok`, or by a text body that matches `text`, whose first capture is the message.
"""
struct ErrorRule
    json_field::Union{Nothing, String}
    json_ok::Union{Nothing, String}
    text::Union{Nothing, Regex}
end

"How failed requests to service `s` are recognised, beyond their HTTP status."
errors(::Service) = NoErrors()

"""
    ServiceError(message, response)

A request that the service reported as failed in a successful HTTP response.
"""
struct ServiceError <: Exception
    message::String
    response::HTTP.Response
end
Base.showerror(io::IO, e::ServiceError) = print(io, "ServiceError: ", e.message)


# Endpoints
# ---------

"""
    Endpoint{S<:Service, M}

Supertype of the request types, one per operation of service `S`; `M` is the HTTP method as a `Symbol`.
Fields tagged `&(in = :path,)` fill the path template, the field tagged `&(in = :body,)` is the request body and every other field that is not `nothing` is a query parameter.
A path field that is `nothing` drops its segment from the path, and a `Bool` path field tagged `literal = "word"` is the segment `word` when `true` and no segment otherwise.
"""
abstract type Endpoint{S<:Service, M} end

service(::Endpoint{S}) where {S} = S()
method(::Endpoint{S, M}) where {S, M} = String(M)

"The path template of an endpoint type, such as `\"/content/{version}/CUI/{CUI}\"`."
function template end

defaultformat(e::Endpoint) = defaultformat(service(e))

_in(::Type{E}, field) where {E} = get(_tags(E, field), :in, :query)
_tags(::Type{E}, field) where {E} = StructUtils.fieldtags(StructUtils.DefaultStyle(), E, field)
_fields(::Type{E}, location) where {E} = filter(f -> _in(E, f) === location, fieldnames(E))

"""
A list parameter: a string as the service expects it, such as `"MSH,SNOMEDCT_US"`, or a vector, such as `["MSH", "SNOMEDCT_US"]`.
A vector is joined with commas, or with the separator its field is tagged with, as in `&(sep = "|",)`.
"""
const ListParam = Union{AbstractString, AbstractVector}

_value(x, sep = ",") = string(x)
_value(x::AbstractVector, sep = ",") = join(map(_value, x), sep)

# One path segment for field `f`, or `nothing` to leave the segment out.
function _segment(::Type{E}, f, x) where {E}
    literal = get(_tags(E, f), :literal, nothing)
    literal === nothing || return x === true ? literal : nothing
    return x === nothing ? nothing : HTTP.escapeuri(_value(x))
end

function path(e::E) where {E<:Endpoint}
    segments = map(split(template(E), '/')) do seg
        m = match(r"^\{(\w+)\}$", seg)
        m === nothing && return seg
        f = Symbol(m[1])
        return _segment(E, f, getfield(e, f))
    end
    return join(filter(!isnothing, segments), "/")
end

query(e::E) where {E<:Endpoint} =
    Pair{String, String}[String(f) => _value(getfield(e, f), get(_tags(E, f), :sep, ",")) for f in _fields(E, :query) if getfield(e, f) !== nothing]

body(e::E) where {E<:Endpoint} = (b = _fields(E, :body); isempty(b) ? nothing : getfield(e, only(b)))

"""
    url(e::Endpoint; accept = defaultformat(e))

The full URL of a request, without the credentials that `send` adds.
"""
function url(e::Endpoint; accept = defaultformat(e))
    s = service(e)
    p, q = _select(s, formatby(s), Format(s, accept), path(e), query(e), Pair{String, String}[])
    return base_url(s) * p * (isempty(q) ? "" : "?" * HTTP.escapeuri(q))
end

# A copy of `e` with some fields replaced, through the keyword constructor @kwarg defines.
_with(e::E; kwargs...) where {E<:Endpoint} =
    Base.typename(E).wrapper(; (f => getfield(e, f) for f in fieldnames(E))..., kwargs...)


# Formats
# -------

"""
    Format{S}

A response format, the type `decode` dispatches on; `S` is its shorthand, such as `:json` or `:gff`.
`Format(s, :gff)` and `Format(s, "text/x-gff")` check the format against the formats of service `s` before any request is made.
"""
struct Format{S} end

Format(s::Service, f::Format{S}) where {S} = Format(s, S)
Format(s::Service, f::Symbol) = haskey(formats(s), f) ? Format{f}() :
    throw(ArgumentError("unknown format :$f; use one of $(join(keys(formats(s)), ", "))"))
function Format(s::Service, m::AbstractString)
    for (f, v) in pairs(formats(s))
        v == m && return Format{f}()
    end
    throw(ArgumentError("unknown format $(repr(m)); use one of $(join(values(formats(s)), ", "))"))
end

mime(s::Service, ::Format{S}) where {S} = formats(s)[S]

# The path and query of a request to service `s`, after asking for format `f`.
_select(s, ::ByHeader, f, p, q, headers) = (push!(headers, "Accept" => mime(s, f)); (p, q))
_select(s, ::ByExtension, ::Format{S}, p, q, headers) where {S} = (p * "." * String(S), q)
_select(s, b::ByQuery, ::Format{S}, p, q, headers) where {S} = (p, push!(q, b.name => String(S)))

"""
    decode(::Format, resp::HTTP.Response)

Turn a response body into a value: JSON is parsed with `JSON.parse`, and any other format is returned as a `String`.
"""
decode(::Format, resp) = String(copy(resp.body))
decode(::Format{:json}, resp) = (text = String(copy(resp.body)); isempty(text) ? nothing : JSON.parse(text))

"""
    decode(::Format, resp::HTTP.Response, T::Type)

Decode a response body into a value of type `T`.
JSON is decoded with `JSON.parse(body, T)`; package extensions add methods for other formats, such as `Vector{GFF3.Record}` from `:gff` once GFF3 is loaded.
A request for a type with no method for its format throws an `ArgumentError` before it is sent.
"""
decode(::Format{:json}, resp, ::Type{T}) where {T} = JSON.parse(String(copy(resp.body)), T)

"""
    defaultformat(T::Type)

The format requested to decode a response into `T` when `send` is given no `accept`, or `nothing` for the service's default.
The extensions that add `decode` methods set it, so `Vector{GFF3.Record}` requests `:gff`.
"""
defaultformat(::Type) = nothing

_decodable(::Format, ::Bool) = nothing
_decodable(::Format{:json}, ::Type) = nothing
function _decodable(f::Format{S}, ::Type{T}) where {S, T}
    hasmethod(decode, Tuple{typeof(f), HTTP.Response, Type{T}}) && return
    throw(ArgumentError("no decoder from :$S to $T; it may need a package to be loaded, such as GFF3"))
end

# Decoding with the service's envelope, which only JSON responses have, removed.
_unwrap(s::Service, data) = (field = envelope(s); field === nothing ? data : data[field])

_decode(s, f, resp, ::Bool) = decode(f, resp)
_decode(s, f::Format{:json}, resp, ::Bool) = _unwrap(s, decode(f, resp))
_decode(s, f, resp, ::Type{T}) where {T} = decode(f, resp, T)
function _decode(s, f::Format{:json}, resp, ::Type{T}) where {T}
    envelope(s) === nothing && return decode(f, resp, T)
    return JSON.parse(JSON.json(_decode(s, f, resp, true)), T)
end


# Requests
# --------

"""
    send(e::Endpoint; accept = defaultformat(e), parse = true)
    send(e::Endpoint, T::Type; accept = defaultformat(T))

Run a request.
With `parse = true` the response is passed to `decode`, and the service's envelope is removed; with `parse = false` the `HTTP.Response` is returned.
With a type, the response is decoded into `T`: JSON with `JSON.parse(body, T)`, for example into a `@kwarg` struct with the fields you need, and other formats by the `decode(::Format, resp, T)` methods that are defined.
"""
send(e::Endpoint; accept = defaultformat(e), parse::Bool = true) = _send(e, Format(service(e), accept), parse)
send(e::Endpoint, ::Type{T}; accept = something(defaultformat(T), defaultformat(e))) where {T} =
    _send(e, Format(service(e), accept), T)

function _send(e::Endpoint, f::Format, parse)
    _decodable(f, parse)
    resp = _response(e, f)
    return parse === false ? resp : _decode(service(e), f, resp, parse)
end

function _response(e::Endpoint, f::Format)
    s = service(e)
    headers = Pair{String, String}[]
    p, q = _select(s, formatby(s), f, path(e), query(e), headers)
    _authorise!(auth(s), q, headers)
    kwargs = _body!(headers, Dict{Symbol, Any}(), body(e))
    isempty(q) || (kwargs[:query] = q)
    resp = _request(method(e), base_url(s) * p, headers; kwargs...)
    _check(errors(s), f, resp)
    return resp
end

_key(env) = get(() -> throw(ArgumentError("this service needs an API key; set ENV[\"$env\"]")), ENV, env)

_authorise!(::NoAuth, q, headers) = nothing
_authorise!(a::QueryKey, q, headers) = push!(q, a.name => _key(a.env))
_authorise!(a::HeaderKey, q, headers) = push!(headers, a.name => _key(a.env))

_check(::NoErrors, f, resp) = nothing
_check(r::ErrorRule, f, resp) = _check(r, f, resp, String(copy(resp.body)))
function _check(r::ErrorRule, ::Format{:json}, resp, text)
    r.json_field === nothing && return
    data = JSON.parse(text)
    data isa AbstractDict && haskey(data, r.json_field) || return
    msg = data[r.json_field]
    msg == r.json_ok || throw(ServiceError(string(msg), resp))
    return
end
function _check(r::ErrorRule, f, resp, text)
    r.text === nothing && return
    m = match(r.text, text)
    m === nothing || throw(ServiceError(something(m[1], m.match), resp))
    return
end

# HTTP 429 is retried, honouring Retry-After.
function _request(method, url, headers; tries = 4, kwargs...)
    for i in 1:tries
        try
            return HTTP.request(method, url, headers; kwargs...)
        catch err
            (err isa HTTP.StatusError && err.status == 429 && i < tries) || rethrow()
            wait = tryparse(Int, HTTP.header(err.response, "Retry-After", ""))
            sleep(something(wait, 2^i))
        end
    end
end

# Request body encoding, by the type of the body.
_body!(headers, kwargs, ::Nothing) = kwargs
function _body!(headers, kwargs, body::AbstractString)
    push!(headers, "Content-Type" => "text/plain")
    kwargs[:body] = String(body)
    return kwargs
end
function _body!(headers, kwargs, body)
    push!(headers, "Content-Type" => "application/json")
    kwargs[:body] = JSON.json(body)
    return kwargs
end


# Paging
# ------

"""
    Pages{E<:Endpoint, P, F<:Format}

Iterator over the pages of a list, returned by `paginate`.
"""
struct Pages{E<:Endpoint, P, F<:Format}
    endpoint::E
    paging::P
    format::F
end

"""
    paginate(e::Endpoint; accept = defaultformat(e))

Iterate over a list one decoded page at a time, from the page `e` asks for, as the service's paging strategy describes.
It throws an `ArgumentError` for a service without paging, or an endpoint without the paging fields.

    for page in paginate(UMLS.ConceptRelations(CUI = "C0009044", pageSize = 50))
        ...
    end
"""
function paginate(e::Endpoint; accept = defaultformat(e))
    p = paging(service(e))
    _pageable(p, e)
    return Pages(e, p, Format(service(e), accept))
end

_pageable(::NoPaging, e) = throw(ArgumentError("$(nameof(parentmodule(typeof(e)))) does not page its lists"))
_pageable(p::PageNumber, e) = hasfield(typeof(e), Symbol(p.number)) ||
    throw(ArgumentError("$(nameof(typeof(e))) has no $(p.number) field, so it is not paged"))

Base.IteratorSize(::Type{<:Pages}) = Base.SizeUnknown()

function Base.iterate(pages::Pages{<:Endpoint, PageNumber}, n = something(getfield(pages.endpoint, Symbol(pages.paging.number)), 1))
    n === nothing && return nothing
    e = _with(pages.endpoint; Symbol(pages.paging.number) => n)
    raw = decode(pages.format, _response(e, pages.format))
    count = get(raw, pages.paging.count, n)
    return _unwrap(service(e), raw), n < count ? n + 1 : nothing
end

end # module
